  /**
   * Render a sprite matrix to a 2D canvas context.
   */
  function drawSprite(ctx, matrix, x, y, scale, color) {
    if (!matrix || !matrix.length) return;
    ctx.fillStyle = color;
    const h = matrix.length;
    const w = matrix[0].length;
    for (let r = 0; r < h; r++) {
      for (let c = 0; c < w; c++) {
        if (matrix[r][c]) {
          ctx.fillRect(Math.floor(x + c * scale), Math.floor(y + r * scale), scale, scale);
        }
      }
    }
  }

  /**
   * Render arcade 5x7 text to canvas context.
   */
  function drawText(ctx, text, x, y, scale, color) {
    ctx.fillStyle = color;
    const str = String(text).toUpperCase();
    let cx = x;
    const charW = 5 * scale;
    const charSpacing = 1 * scale;

    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      const fontMatrix = FONT_5X7[ch] || FONT_5X7[' '];
      for (let r = 0; r < 7; r++) {
        for (let c = 0; c < 5; c++) {
          if (fontMatrix[r][c]) {
            ctx.fillRect(Math.floor(cx + c * scale), Math.floor(y + r * scale), scale, scale);
          }
        }
      }
      cx += charW + charSpacing;
    }
  }

  // Export engine
